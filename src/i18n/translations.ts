export const translations = { en, ar };

export function translate(
  lang: AppLanguage,
  key: TranslationKey,
  vars?: Record<string, string | number>,
): string {
  let text = translations[lang][key] || translations.en[key] || String(key);
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }
  return text;
}

export function requestTypeKey(
  type: string,
): TranslationKey {
  const map: Record<string, TranslationKey> = {
    vacation: 'typeVacation',
    sick: 'typeSick',
    unpaid: 'typeUnpaid',
    business_trip: 'typeBusinessTrip',
    early_leave: 'typeEarlyLeave',
    late_arrive: 'typeLateArrive',
    missing: 'typeMissing',
  };
  return map[type] || 'requestsTitle';
}
